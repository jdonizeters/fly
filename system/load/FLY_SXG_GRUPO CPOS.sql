-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_SXG_GRUPO_CPOS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_SXG_GRUPO_CPOS (
        XG_GRUPO   VARCHAR(10)  NOT NULL,
        XG_DESCRI  VARCHAR(255) NULL,
        XG_SIZEMAX INT          NULL,
        XG_SIZEMIN INT          NULL,
        XG_SIZE    INT          NULL,
        XG_PICTURE VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_SXG_GRUPO_CPOS PRIMARY KEY (XG_GRUPO)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_SXG_GRUPO_CPOS;

INSERT INTO FLY_SXG_GRUPO_CPOS (
    XG_GRUPO,
    XG_DESCRI,
    XG_SIZEMAX,
    XG_SIZEMIN,
    XG_SIZE,
    XG_PICTURE
)
SELECT
    XG_GRUPO,
    XG_DESCRI,
    CAST(XG_SIZEMAX AS INT) AS XG_SIZEMAX,
    CAST(XG_SIZEMIN AS INT) AS XG_SIZEMIN,
    CAST(XG_SIZE AS INT) AS XG_SIZE,
    XG_PICTURE
FROM
    SXG990
WHERE
    D_E_L_E_T_ = ' '
ORDER BY
    XG_GRUPO;