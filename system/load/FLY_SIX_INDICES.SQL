-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_SIX_INDICES', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_SIX_INDICES (
        INDICE    VARCHAR(10)  NOT NULL,
        ORDEM     VARCHAR(10)  NOT NULL,
        CHAVE     VARCHAR(255) NULL,
        DESCRICAO VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_SIX_INDICES PRIMARY KEY (INDICE, ORDEM)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_SIX_INDICES;

INSERT INTO FLY_SIX_INDICES (
    INDICE,
    ORDEM,
    CHAVE,
    DESCRICAO
)
SELECT 
    INDICE, 
    ORDEM, 
    CHAVE, 
    DESCRICAO 
FROM SIX990
WHERE
    D_E_L_E_T_ = ' '
ORDER BY INDICE, ORDEM;