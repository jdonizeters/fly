-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_SX6_PARAMETROS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_SX6_PARAMETROS (
        X6_VAR     VARCHAR(50)  NOT NULL,
        X6_TIPO    VARCHAR(10)  NULL,
        X6_DESCRIC VARCHAR(MAX) NULL,
        X6_CONTEUD VARCHAR(MAX) NULL,
        CONSTRAINT PK_FLY_SX6_PARAMETROS PRIMARY KEY (X6_VAR)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_SX6_PARAMETROS;

INSERT INTO FLY_SX6_PARAMETROS (
    X6_VAR,
    X6_TIPO,
    X6_DESCRIC,
    X6_CONTEUD
)
SELECT
    X6_VAR,
    X6_TIPO,
    TRIM(X6_DESCRIC) + ' ' + TRIM(X6_DESC1) + ' ' + TRIM(X6_DESC2) AS X6_DESCRIC,
    X6_CONTEUD
FROM
    SX6990
WHERE
    D_E_L_E_T_ = ' '
    AND X6_FIL = ' '
ORDER BY
    X6_VAR;