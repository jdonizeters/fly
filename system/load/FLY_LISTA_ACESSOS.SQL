-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_LISTA_ACESSOS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_LISTA_ACESSOS (
        CODIGO    INT          NOT NULL,
        DESCRICAO VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_LISTA_ACESSOS PRIMARY KEY (CODIGO)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_LISTA_ACESSOS;

INSERT INTO FLY_LISTA_ACESSOS (
    CODIGO,
    DESCRICAO
)
SELECT 
    CAST(GR__CODACESSO AS INT) AS CODIGO, 
    GR__DESCACESSO AS DESCRICAO
FROM SYS_GRP_ACCESS
WHERE D_E_L_E_T_ = ' '
  AND GR__ID = '000000'
ORDER BY GR__CODACESSO;