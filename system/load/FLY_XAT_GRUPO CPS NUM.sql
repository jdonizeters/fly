-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_XAT_GRUPO_CPS_NUM', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_XAT_GRUPO_CPS_NUM (
        XAT_CODE   VARCHAR(10)  NOT NULL,
        XAT_DSCPOR VARCHAR(255) NULL,
        XAT_SIZE   INT          NULL,
        XAT_DECIMA INT          NULL,
        XAT_PICTUR VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_XAT_GRUPO_CPS_NUM PRIMARY KEY (XAT_CODE)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_XAT_GRUPO_CPS_NUM;

INSERT INTO FLY_XAT_GRUPO_CPS_NUM (
    XAT_CODE,
    XAT_DSCPOR,
    XAT_SIZE,
    XAT_DECIMA,
    XAT_PICTUR
)
SELECT 
    XAT_CODE, 
    XAT_DSCPOR, 
    CAST(XAT_SIZE AS INT) AS XAT_SIZE,
    CAST(XAT_DECIMA AS INT) AS XAT_DECIMA,
    XAT_PICTUR 
FROM XAT990
WHERE
    D_E_L_E_T_ = ' '
ORDER BY XAT_CODE;