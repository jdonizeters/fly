-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_SX3_CAMPOS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_SX3_CAMPOS (
        X3_CAMPO    VARCHAR(10)  NOT NULL,
        X3_TITULO   VARCHAR(255) NULL,
        X3_DESCRIC  VARCHAR(255) NULL,
        X3_ORDEM    VARCHAR(5)   NULL,
        X3_TIPO     VARCHAR(5)   NULL,
        X3_TAMANHO  INT          NULL,
        X3_DECIMAL  INT          NULL,
        X3_ARQUIVO  VARCHAR(10)  NULL,
        X3_RESERV   VARCHAR(50)  NULL,
        X3_OBRIGAT  VARCHAR(5)   NULL,
        X3_RELACAO  VARCHAR(MAX) NULL,
        X3_VISUAL   VARCHAR(5)   NULL,
        X3_CBOX     VARCHAR(MAX) NULL,
        X3_FOLDER   VARCHAR(255) NULL,
        X3_GRPSXG   VARCHAR(255) NULL,
        XAU_CODE    VARCHAR(255) NULL,
        D_E_L_E_T_  VARCHAR(1)   NULL,
        CONSTRAINT PK_FLY_SX3_CAMPOS PRIMARY KEY (X3_CAMPO)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_SX3_CAMPOS;

INSERT INTO FLY_SX3_CAMPOS (
    X3_CAMPO,
    X3_TITULO,
    X3_DESCRIC,
    X3_ORDEM,
    X3_TIPO,
    X3_TAMANHO,
    X3_DECIMAL,
    X3_ARQUIVO,
    X3_RESERV,
    X3_OBRIGAT,
    X3_RELACAO,
    X3_VISUAL,
    X3_CBOX,
    X3_FOLDER,
    X3_GRPSXG,
    XAU_CODE,
    D_E_L_E_T_
)
SELECT
    SX3.X3_CAMPO, 
    SX3.X3_TITULO, 
    SX3.X3_DESCRIC, 
    SX3.X3_ORDEM, 
    SX3.X3_TIPO,
    CAST(SX3.X3_TAMANHO AS INT) AS X3_TAMANHO,
    CAST(SX3.X3_DECIMAL AS INT) AS X3_DECIMAL,
    SX3.X3_ARQUIVO, 
    SX3.X3_RESERV,
    CASE WHEN (SUBSTRING(SX3.X3_RESERV, 7, 1) = 'x' OR SUBSTRING(SX3.X3_OBRIGAT, 1, 1) = 'x') THEN 'sim' ELSE 'não' END AS X3_OBRIGAT,
    SX3.X3_RELACAO, 
    SX3.X3_VISUAL, 
    SX3.X3_CBOX, 
    LEFT(SX3.X3_FOLDER + ' - ' + COALESCE(SXA.XA_DESCRIC, ''), 255) AS X3_FOLDER, 
    LEFT(SX3.X3_GRPSXG + ' - ' + COALESCE(SXG.XG_DESCRI, ''), 255) AS X3_GRPSXG,
    LEFT(COALESCE(XAU.XAU_CODE + ' - ' + XAT.XAT_DSCPOR, ' '), 255) AS XAU_CODE,
    SX3.D_E_L_E_T_
FROM
    SX3990 SX3 WITH (NOLOCK)
    OUTER APPLY (
        SELECT TOP 1 XG_DESCRI 
        FROM SXG990 WITH (NOLOCK) 
        WHERE D_E_L_E_T_ = ' ' AND XG_GRUPO = SX3.X3_GRPSXG
    ) SXG
    OUTER APPLY (
        SELECT TOP 1 XAU_CODE 
        FROM XAU990 WITH (NOLOCK) 
        WHERE D_E_L_E_T_ = ' ' AND XAU_KEY = SX3.X3_CAMPO
    ) XAU
    OUTER APPLY (
        SELECT TOP 1 XAT_DSCPOR 
        FROM XAT990 WITH (NOLOCK) 
        WHERE D_E_L_E_T_ = ' ' AND XAT_CODE = XAU.XAU_CODE
    ) XAT
    OUTER APPLY (
        SELECT TOP 1 XA_DESCRIC 
        FROM SXA990 WITH (NOLOCK) 
        WHERE D_E_L_E_T_ = ' ' AND XA_ALIAS = SX3.X3_ARQUIVO AND XA_ORDEM = SX3.X3_FOLDER AND XA_AGRUP = ' '
    ) SXA
WHERE
    SX3.D_E_L_E_T_ = ' '
    AND SX3.X3_CONTEXT <> 'V';