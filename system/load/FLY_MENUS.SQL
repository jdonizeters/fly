-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_MENUS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_MENUS (
        M_NAME     VARCHAR(255) NULL,
        N_DESC1    VARCHAR(255) NULL,
        F_FUNCTION VARCHAR(255) NULL
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_MENUS;

INSERT INTO FLY_MENUS (
    M_NAME,
    N_DESC1,
    F_FUNCTION
)
SELECT 
    TRIM(MPN.M_NAME) AS M_NAME,
    CASE 
        WHEN MPI.I_ID_FUNC = ' ' THEN UPPER(I18N1.N_DESC) 
        ELSE '    ' + I18N1.N_DESC 
    END AS N_DESC1,
    TRIM(COALESCE(MPF.F_FUNCTION, '')) AS F_FUNCTION
FROM MPMENU_MENU MPN
INNER JOIN MPMENU_ITEM MPI 
    ON MPI.I_ID_MENU = MPN.M_ID 
    AND MPI.D_E_L_E_T_ = ' '
LEFT JOIN MPMENU_FUNCTION MPF 
    ON MPF.F_ID = MPI.I_ID_FUNC 
    AND MPF.D_E_L_E_T_ = ' '
INNER JOIN MPMENU_I18N I18N1 
    ON I18N1.N_PAREN_ID = MPI.I_ID 
    AND I18N1.N_LANG = '1' 
    AND I18N1.D_E_L_E_T_ = ' '
INNER JOIN MPMENU_I18N I18N2 
    ON I18N2.N_PAREN_ID = MPI.I_ID 
    AND I18N2.N_LANG = '2' 
    AND I18N2.D_E_L_E_T_ = ' '
INNER JOIN MPMENU_I18N I18N3 
    ON I18N3.N_PAREN_ID = MPI.I_ID 
    AND I18N3.N_LANG = '3' 
    AND I18N3.D_E_L_E_T_ = ' '
LEFT JOIN MPMENU_KEY_WORDS KW1 
    ON KW1.K_ID_ITEM = MPI.I_ID 
    AND KW1.K_LANG = '1' 
    AND KW1.D_E_L_E_T_ = ' '
LEFT JOIN MPMENU_KEY_WORDS KW2 
    ON KW2.K_ID_ITEM = MPI.I_ID 
    AND KW2.K_LANG = '2' 
    AND KW2.D_E_L_E_T_ = ' '
LEFT JOIN MPMENU_KEY_WORDS KW3 
    ON KW3.K_ID_ITEM = MPI.I_ID 
    AND KW3.K_LANG = '3' 
    AND KW3.D_E_L_E_T_ = ' '
ORDER BY MPN.M_NAME, MPI.I_ORDER;