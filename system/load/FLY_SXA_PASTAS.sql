-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_SXA_PASTAS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_SXA_PASTAS (
        XA_ALIAS   VARCHAR(10)  NOT NULL,
        XA_ORDEM   VARCHAR(5)   NOT NULL,
        XA_DESCRIC VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_SXA_PASTAS PRIMARY KEY (XA_ALIAS, XA_ORDEM)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_SXA_PASTAS;

INSERT INTO FLY_SXA_PASTAS (
    XA_ALIAS,
    XA_ORDEM,
    XA_DESCRIC
)
SELECT
    XA_ALIAS,
    XA_ORDEM,
    XA_DESCRIC
FROM
    SXA990
WHERE
    D_E_L_E_T_ = ' '
    AND XA_AGRUP = ' '
ORDER BY
    XA_ALIAS,
    XA_ORDEM;