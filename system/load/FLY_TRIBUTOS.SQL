-- CRIAÇÃO DA TABELA (somente se não existir)
IF OBJECT_ID('dbo.FLY_TRIBUTOS', 'U') IS NULL
BEGIN
    CREATE TABLE FLY_TRIBUTOS (
        F2E_TRIB   VARCHAR(20)  NOT NULL,
        F2E_DESC   VARCHAR(255) NULL,
        F2E_ESFERA VARCHAR(50)  NULL,
        F2E_ESPECI VARCHAR(50)  NULL,
        F2E_IDTRIB VARCHAR(255) NULL,
        CONSTRAINT PK_FLY_TRIBUTOS PRIMARY KEY (F2E_TRIB)
    );
END;

-- LIMPEZA E INSERÇÃO DOS DADOS
TRUNCATE TABLE FLY_TRIBUTOS;

INSERT INTO FLY_TRIBUTOS (
    F2E_TRIB,
    F2E_DESC,
    F2E_ESFERA,
    F2E_ESPECI,
    F2E_IDTRIB
)
SELECT 
    F2E_TRIB, 
    F2E_DESC, 
    CASE
        WHEN F2E_ESFERA = '1' THEN '1-Federal'
        WHEN F2E_ESFERA = '2' THEN '2-Estadual'
        WHEN F2E_ESFERA = '3' THEN '3-Municipal'
        ELSE F2E_ESFERA + '-?'
    END AS F2E_ESFERA,
    CASE
        WHEN F2E_ESPECI = '1' THEN '1-Imposto'
        WHEN F2E_ESPECI = '2' THEN '2-Contribuição'
        WHEN F2E_ESPECI = '3' THEN '3-Fundo'
        WHEN F2E_ESPECI = '4' THEN '4-Taxa'
        ELSE F2E_ESPECI + '-?'
    END AS F2E_ESPECI,
    F2E_IDTRIB + ' - ' + ISNULL(F2C_DESC, '') AS F2E_IDTRIB 
FROM F2E990 F2E
LEFT JOIN F2C990 F2C ON
    F2C_CODIGO = F2E_IDTRIB AND
    F2C.D_E_L_E_T_ = ' '
WHERE
    F2E.D_E_L_E_T_ = ' '
ORDER BY F2E_TRIB;